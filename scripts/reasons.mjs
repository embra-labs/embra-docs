// Sync the metadata row under each /loi/ heading from the product's reason registry (api/reasons.go).
//
//   node scripts/reasons.mjs            # rewrite src/data/reasons.json + both /loi/ pages
//   node scripts/reasons.mjs --check    # exit 1 if anything is out of date or a code has no entry
//
// Source: `git show origin/main:api/reasons.go` in EMBRA_REPO (default ../embra). CI does not have the
// product repo, so the generated JSON and tables are committed; run this after every reason change.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const repo = process.env.EMBRA_REPO ?? new URL('../../embra', import.meta.url).pathname;
const ref = process.env.EMBRA_REF ?? 'origin/main';
const check = process.argv.includes('--check');

const src = execFileSync('git', ['-C', repo, 'show', `${ref}:api/reasons.go`], { encoding: 'utf8' });
const commit = execFileSync('git', ['-C', repo, 'rev-parse', '--short', ref], { encoding: 'utf8' }).trim();

// apigen.ReasonCodeSCHEMADRIFT: {409, false, apigen.NextActionRerunPlan, 10},
const enumName = (s) => s.replace(/^ReasonCode/, '');
const actionName = { None: 'none', Wait: 'wait', OwnerReview: 'owner_review', FixInput: 'fix_input', RerunPlan: 'rerun_plan', ContactOperator: 'contact_operator' };
const rows = [...src.matchAll(/apigen\.(ReasonCode\w+):\s*\{(\d+),\s*(true|false),\s*apigen\.NextAction(\w+),\s*(\d+)\}/g)].map((m) => ({
	key: enumName(m[1]),
	http: Number(m[2]),
	retryable: m[3] === 'true',
	next_action: actionName[m[4]] ?? m[4],
	exit: Number(m[5]),
}));
// Real code strings (SCHEMA_DRIFT) come from the ReasonCode enum in api/openapi.yaml.
const spec = execFileSync('git', ['-C', repo, 'show', `${ref}:api/openapi.yaml`], { encoding: 'utf8' });
const enumBlock = spec.match(/\n    ReasonCode:\n[\s\S]*?enum:\n((?:\s+- [A-Z0-9_]+\n)+)/);
if (!enumBlock) throw new Error('ReasonCode enum not found in api/openapi.yaml');
const codeByKey = new Map([...enumBlock[1].matchAll(/- ([A-Z0-9_]+)/g)].map((m) => [m[1].replaceAll('_', ''), m[1]]));
for (const r of rows) {
	r.code = codeByKey.get(r.key);
	if (!r.code) throw new Error(`${r.key} is in reasons.go but not in the openapi ReasonCode enum`);
}
if (rows.length < 40) throw new Error(`parsed only ${rows.length} reasons; reasons.go format changed?`);

// The Go enum name drops underscores (SCHEMADRIFT); the /loi/ heading has them (SCHEMA_DRIFT). Match by
// stripping underscores from the headings.
const norm = (code) => code.replaceAll('_', '');

// Next command per code. Only commands that exist on the product's main; contact_operator never gets one.
const next = {
	vi: {
		fix_input: 'Sửa theo mục này rồi làm lại',
		rerun_plan: 'Tạo plan mới: **"Build lại"** hoặc `embra build`',
		owner_review: 'Owner hoặc Admin xem trên web',
		wait: '`embra wait <op_id>`, hoặc chờ rồi thử lại',
		contact_operator: 'Không có, cố ý. Email hello@embra.cloud kèm `operation_id`',
		none: '',
	},
	en: {
		fix_input: 'Fix as described here, then retry',
		rerun_plan: 'New plan: **"Build lại"** (rebuild) or `embra build`',
		owner_review: 'Owner or Admin reviews on the web',
		wait: '`embra wait <op_id>`, or wait and retry',
		contact_operator: 'None, on purpose. Email hello@embra.cloud with the `operation_id`',
		none: '',
	},
};
const override = {
	MIGRATION_DATA_LOSS: { vi: 'Approve trên web, gõ `CONFIRM_MIGRATION`', en: 'Approve on the web, type `CONFIRM_MIGRATION`' },
	MIGRATION_REHEARSAL_FAILED: { vi: 'Sửa SQL, kiểm bằng `embra plan` rồi push', en: 'Fix the SQL, check with `embra plan`, then push' },
	MIGRATION_UNSUPPORTED: { vi: 'Bỏ câu lệnh lớp E/F, push lại', en: 'Remove the class E/F statement, push again' },
	MIGRATION_HISTORY_CHANGED: { vi: '`git checkout <commit> -- migrations/<file>`', en: '`git checkout <commit> -- migrations/<file>`' },
	ROLLBACK_INCOMPATIBLE: { vi: 'Sửa bằng commit mới', en: 'Fix forward with a new commit' },
	MIGRATION_AFTER_RESTORE_POINT: { vi: 'Chọn mốc sau migration', en: 'Pick a point after the migration' },
	RESTORE_POINT_UNAVAILABLE: { vi: '`embra db restore-points`', en: '`embra db restore-points`' },
	OPERATION_IN_PROGRESS: { vi: '`embra wait <op_id>`', en: '`embra wait <op_id>`' },
	UNAUTHENTICATED: { vi: '`embra login` hoặc token mới', en: '`embra login` or a new token' },
	API_UNREACHABLE: { vi: 'Kiểm `--api`/`EMBRA_API` và mạng, chạy lại', en: 'Check `--api`/`EMBRA_API` and the network, rerun' },
};

const head = {
	vi: '| HTTP | Retry tự động | `next_action` | Exit code | Lệnh tiếp |',
	en: '| HTTP | Auto retry | `next_action` | Exit code | Next step |',
};
const yes = { vi: ['Có', 'Không'], en: ['Yes', 'No'] };
// HTTP 0 in reasons.go = raised by the CLI / embra mcp itself, never sent by the server.
const clientOnly = { vi: '— (CLI)', en: '— (CLI)' };
const START = '<!-- reason-meta: generated by scripts/reasons.mjs, do not edit -->';
const END = '<!-- /reason-meta -->';

function table(lang, code, r) {
	const step = override[code]?.[lang] ?? next[lang][r.next_action];
	return [START, '', head[lang], '|---|---|---|---|---|',
		`| ${r.http === 0 ? clientOnly[lang] : r.http} | ${r.retryable ? yes[lang][0] : yes[lang][1]} | \`${r.next_action}\` | \`${r.exit}\` | ${step} |`, '', END].join('\n');
}

const byNorm = new Map(rows.map((r) => [r.key, r]));
let stale = false;
const problems = [];

for (const [lang, path] of [['vi', 'src/content/docs/loi/index.md'], ['en', 'src/content/docs/en/loi/index.md']]) {
	const file = new URL(`../${path}`, import.meta.url);
	const before = readFileSync(file, 'utf8');
	// Drop old generated blocks, then insert a fresh one under each code heading.
	let text = before.replace(new RegExp(`${START}[\\s\\S]*?${END}\\n\\n`, 'g'), '');
	const seen = new Set();
	text = text.replace(/^### `([A-Z0-9_]+)`\n/gm, (line, code) => {
		const r = byNorm.get(norm(code));
		if (!r) {
			problems.push(`${lang}: /loi/ has ${code} but api/reasons.go does not`);
			return line;
		}
		seen.add(r.key);
		r.docs ??= {};
		r.docs[lang] = `https://docs.embra.cloud${lang === 'en' ? '/en' : ''}/loi/#${code.toLowerCase()}`;
		r.next_step ??= {};
		r.next_step[lang] = (override[code]?.[lang] ?? next[lang][r.next_action]).replace(/\*\*/g, '');
		return `${line}\n${table(lang, code, r)}\n`;
	});
	for (const r of rows) {
		// OK/ACCEPTED/APPROVAL_REQUIRED are not errors (cli/errordocs_test.go); device-flow codes are internal to `embra login`.
		if (!seen.has(r.key) && r.exit !== 0 && !r.key.startsWith('DEVICEAUTHORIZATION') && r.key !== 'DEVICESLOWDOWN') {
			problems.push(`${lang}: ${r.key} has no /loi/ entry`);
		}
	}
	if (text !== before) {
		stale = true;
		if (!check) writeFileSync(file, text);
	}
}

const out = rows.map(({ code, http, retryable, next_action, exit, docs, next_step }) =>
	({ code, http, retryable, next_action, exit, docs: docs ?? null, next_step: next_step ?? null }));
const json = JSON.stringify({ source: `embra ${commit} api/reasons.go`, reasons: out }, null, '\t') + '\n';
const jsonFile = new URL('../src/data/reasons.json', import.meta.url);
let oldJson = '';
try { oldJson = readFileSync(jsonFile, 'utf8'); } catch {}
// The commit line alone changing is not staleness.
const body = (s) => s.replace(/"source": "[^"]*"/, '');
if (body(oldJson) !== body(json)) {
	stale = true;
	if (!check) { mkdirSync(new URL('../src/data/', import.meta.url), { recursive: true }); writeFileSync(jsonFile, json); }
}

for (const p of problems) console.error(p);
if (check && (stale || problems.length)) {
	console.error(stale ? 'out of date: run node scripts/reasons.mjs' : '');
	process.exit(1);
}
console.log(`${rows.length} reasons from embra ${commit}${check ? ', up to date' : ''}`);
